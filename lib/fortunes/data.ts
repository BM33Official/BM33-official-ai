export interface Fortune {
  id: number;
  tier: TierKey;
  cat: string;
  title: string;
  text: string;
}

export const FORTUNES: Fortune[] = CATEGORIES.flatMap((c) =>
  (RAW[c.key] ?? []).map(([tier, title, text]) => ({ id: 0, tier, cat: c.key, title, text }))
).map((f, i) => ({ ...f, id: i }));

export const TOTAL = FORTUNES.length; // 200
export const CAT_BY_KEY = Object.fromEntries(CATEGORIES.map((c) => [c.key, c])) as Record<string, Category>;

// ── สมุดสะสม: bitset 200 บิต <-> base64url ──────────────────────────────────
export function emptyBits(): Uint8Array {
  return new Uint8Array(Math.ceil(TOTAL / 8));
}
export function decodeBits(s: string): Uint8Array {
  const out = emptyBits();
  if (!s) return out;
  try {
    const b64 = s.replace(/-/g, "+").replace(/_/g, "/");
    const bin = typeof atob === "function" ? atob(b64) : Buffer.from(b64, "base64").toString("binary");
    for (let i = 0; i < Math.min(bin.length, out.length); i++) out[i] = bin.charCodeAt(i);
  } catch { /* ignore */ }
  return out;
}
export function encodeBits(b: Uint8Array): string {
  let bin = "";
  for (let i = 0; i < b.length; i++) bin += String.fromCharCode(b[i]);
  const b64 = typeof btoa === "function" ? btoa(bin) : Buffer.from(bin, "binary").toString("base64");
  return b64.replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}
export function hasBit(b: Uint8Array, i: number): boolean {
  return (b[i >> 3] & (1 << (i & 7))) !== 0;
}
export function setBit(b: Uint8Array, i: number): void {
  b[i >> 3] |= 1 << (i & 7);
}
export function countBits(b: Uint8Array): number {
  let n = 0;
  for (let i = 0; i < TOTAL; i++) if (hasBit(b, i)) n++;
  return n;
}
export function orBits(a: Uint8Array, b: Uint8Array): Uint8Array {
  const out = emptyBits();
  for (let i = 0; i < out.length; i++) out[i] = (a[i] ?? 0) | (b[i] ?? 0);
  return out;
}

