export const PITY_LIMIT = 30; // ไม่เจอ Platinum ขึ้นไปเกิน 30 ครั้ง -> การันตี

// Lucky Hour: ชั่วโมงนำโชคประจำวัน (ทุกเครื่องเห็นตรงกัน — คำนวณจากวันที่) ช่วง 09:00–22:00
export function luckyHour(day: string): number {
  let h = 2166136261;
  for (const ch of `bm33-lucky-${day}`) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619); }
  return 9 + (Math.abs(h) % 13);
}
export const LUCKY_MULT = 2; // Platinum/Diamond/Jackpot ×2 ในชั่วโมงนำโชค
export function streakBonus(streak: number): number { return Math.min(7, Math.max(0, streak)) * 0.05; } // +5%/วัน สูงสุด +35%

export function tierRates(opts: { lucky?: boolean; streak?: number } = {}): Record<TierKey, number> {
  const boost = (opts.lucky ? LUCKY_MULT : 1) * (1 + streakBonus(opts.streak ?? 0));
  const r = Object.fromEntries(TIERS.map((t) => [t.key, TIER_RANK[t.key] >= 3 ? t.rate * boost : t.rate])) as Record<TierKey, number>;
  const total = Object.values(r).reduce((a, b) => a + b, 0);
  for (const k of Object.keys(r) as TierKey[]) r[k] /= total;
  return r;
}

export function rollTier(rng: () => number, opts: { firstOfDay?: boolean; pity?: number; lucky?: boolean; streak?: number } = {}): TierKey {
  const rates = tierRates(opts);
  const pityHit = (opts.pity ?? 0) >= PITY_LIMIT - 1;
  let pool = TIERS.map((t) => t.key);
  if (pityHit) pool = pool.filter((k) => TIER_RANK[k] >= 3);
  else if (opts.firstOfDay) pool = pool.filter((k) => TIER_RANK[k] >= 2); // ใบแรกของวัน: Gold ขึ้นไป
  const total = pool.reduce((a, k) => a + rates[k], 0);
  let r = rng() * total;
  for (const k of pool) {
    if ((r -= rates[k]) <= 0) return k;
  }
  return pool[pool.length - 1];
}

// เลือกใบในระดับนั้น — 70% เลือกใบที่ยังไม่มีในสมุด (ให้สะสมสนุก)
export function pickFortune(rng: () => number, tier: TierKey, collected: Uint8Array): Fortune {
  const inTier = FORTUNES.filter((f) => f.tier === tier);
  const fresh = inTier.filter((f) => !hasBit(collected, f.id));
  const pool = fresh.length && rng() < 0.7 ? fresh : inTier;
  return pool[Math.floor(rng() * pool.length)];
}
